#!/usr/bin/env bash
# Full demo against the compose stack: create group `demo` → deploy → call demo_calculator_tool over MCP, Streamable
# HTTP straight at the worker (CONTRACTS §16: a URL and a bearer header, nothing to install). RAMEN_DEMO_TRANSPORT=bridge
# runs the same call through the stdio bridge over gRPC instead (the compatibility path).
# Console API paths follow CONTRACTS §4a (mirrored by tests/src/ramen_tests/console.py ROUTES).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
CONSOLE=${RAMEN_CONSOLE_URL:-https://localhost:8443}
NODE=${RAMEN_NODE_TARGET:-localhost:8080}
ROOT=$(cd "$HERE/../.." && pwd)
EMAIL=${RAMEN_ADMIN_EMAIL:-admin@ramen.local}
PASS=${RAMEN_ADMIN_PASSWORD:-$(sed -n 's/^RAMEN_ADMIN_PASSWORD=//p' "$HERE/.env" 2>/dev/null)}   # generated by make env
[ -n "$PASS" ] || { echo "no RAMEN_ADMIN_PASSWORD: run make env" >&2; exit 2; }
REPO=${RAMEN_DEMO_REPO:-https://github.com/bkraad47/ramen-demo-mcp-group}
REF=${RAMEN_DEMO_REF:-main}   # main's LLM rails need Config → LLM providers; v0.8.0 is the key-free try-out
JAR=${RAMEN_DEMO_COOKIES:-$HERE/.cookies}
C="curl -sk -c $JAR -b $JAR"
$C -o /dev/null -w "login: %{http_code}\n" -X POST "$CONSOLE/login" -d "email=$EMAIL" -d "password=$PASS"
CSRF=$(awk '$6=="ramen_csrf"{print $7}' "$JAR")   # CONTRACTS §9: cookie sessions send X-Ramen-CSRF on mutations
api() { $C -H 'Content-Type: application/json' -H "X-Ramen-CSRF: $CSRF" -X "$1" "$CONSOLE/api/v1$2" ${3:+-d "$3"}; echo; }
api POST /zones '{"name":"local","provider":"local","region":"local"}'
api POST /groups "{\"name\":\"demo\",\"repo_url\":\"$REPO\",\"ref\":\"$REF\"}"
# §27: an environment naming the zone binds the pair and starts its first deploy at once; a re-run deploys again
ENV=$(api POST /groups/demo/environments "{\"name\":\"dev\",\"ref\":\"$REF\",\"zones\":[\"local\"]}")
echo "$ENV"
deploy() { api POST /groups/demo/environments/dev/deploy '{"canary":true}' | python3 -c 'import sys,json;print(json.load(sys.stdin).get("id") or "")'; }
JOB=$(printf '%s' "$ENV" | python3 -c 'import sys,json;print((json.load(sys.stdin).get("jobs") or [""])[0])' 2>/dev/null || true)
[ -n "$JOB" ] || JOB=$(deploy)
failed() {
  echo "deploy failed: $1"
  case "$1" in *"LLM provider"*)
    echo "the demo's LLM rails need a model: add a key on Config → LLM providers (https://localhost:8443/config), or try"
    echo "the key-free demo: RAMEN_DEMO_REF=v0.8.0 make demo" ;; esac
  exit 1
}
wait_job() {  # ok → 0; error → the error text on stdout, 1
  for _ in $(seq 1 90); do
    J=$(api GET "/jobs/$1")
    S=$(printf '%s' "$J" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("status",""))')
    [ "$S" = ok ] && return 0
    [ "$S" = error ] && { printf '%s' "$J" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("error") or "")'; return 1; }
    sleep 2
  done
  echo "deploy $1 still running after 180 s"; return 1
}
# the first load on a fresh worker pip-installs the repo's requirements and starts NeMo, which can outlast the
# console's 10 s reload deadline (DEADLINE_EXCEEDED); the worker keeps loading, so wait and deploy once more
if ! ERR=$(wait_job "$JOB"); then
  case "$ERR" in *DEADLINE_EXCEEDED*)
    echo "first load still running on the worker ($ERR); deploying again in 30 s"; sleep 30
    JOB=$(deploy); ERR=$(wait_job "$JOB") || failed "$ERR" ;;
  *) failed "$ERR" ;; esac
fi
# §31.1: a repo with `mcp/llm-config/` (the demo's since v1.0.0) mints a key only for a member who accepted its
# configs; §29.3/§31.2/§36.3: the call names every required policy version in `_meta` or the worker refuses it (-32028
# for configs). A repo without them: no accept, no `_meta`.
POLICY=$($C "$CONSOLE/.well-known/ramen-policy?group=demo&zone=local")
CFG=$(printf '%s' "$POLICY" | python3 -c 'import sys,json;print(((json.load(sys.stdin) or {}).get("configs") or {}).get("version") or "")' 2>/dev/null || true)
if [ -n "$CFG" ]; then api POST /groups/demo/configs/accept "{\"version\":\"$CFG\"}" >/dev/null; echo "accepted LLM configs $CFG"; fi
RAMEN_MCP_META=$(printf '%s' "$POLICY" | python3 -c '
import json, sys
keys = {"evals": "io.ramen/evals", "skillspector": "io.ramen/skillspector", "configs": "io.ramen/configs", "guardrails": "io.ramen/guardrails"}
p = json.load(sys.stdin) or {}
print(json.dumps({m: {"version": p[k]["version"]} for k, m in keys.items() if isinstance(p.get(k), dict) and p[k].get("required") and isinstance(p[k].get("version"), str)}))' 2>/dev/null || echo '{}')
export RAMEN_MCP_META   # tests/src/ramen_tests/mcp_client.py POLICY_META, read by mcp_call.py
KEY=$(api POST /groups/demo/mcp-keys "{\"name\":\"demo-$(date +%s)\"}" | python3 -c 'import sys,json;print(json.load(sys.stdin)["key"])')
MCP_URL=${RAMEN_MCP_URL:-https://$NODE/mcp}
# D86: the worker serves TLS with the local CA `certs` generated (deploy/local/.certs)
export RAMEN_CA=${RAMEN_CA:-$HERE/.certs/ca/ca.crt} RAMEN_BRIDGE_CA=${RAMEN_BRIDGE_CA:-$HERE/.certs/ca/ca.crt}
# ready = the worker lists the demo tool over HTTP (a POST /mcp answers 200 as soon as the node is up; the tool
# appears once the runtime has loaded the group's code)
LIST='{"jsonrpc":"2.0","id":1,"method":"tools/list"}'
for _ in $(seq 1 60); do
  curl -s --cacert "$RAMEN_CA" -X POST "$MCP_URL" -H "Authorization: Bearer $KEY" -H 'Content-Type: application/json' -H 'Accept: application/json' \
    -H 'ramen-group: demo' -H 'ramen-zone: local' -d "$LIST" 2>/dev/null | grep -q demo_calculator_tool && break
  sleep 2
done
echo "ready: $MCP_URL lists demo_calculator_tool"
(cd "$ROOT/runtime-py" && uv sync -q --all-extras)
TARGET=$MCP_URL
[ "${RAMEN_DEMO_TRANSPORT:-http}" = bridge ] && TARGET=$NODE   # host:port → mcp_call.py uses the stdio bridge over gRPC
OUT=$(cd "$ROOT/runtime-py" && RAMEN_MCP_GROUP=demo RAMEN_MCP_ZONE=local uv run -q --all-extras python "$HERE/mcp_call.py" "$TARGET" "$KEY" demo_calculator_tool '{"var1": 2, "var2": 3, "func": "add"}')
echo "$OUT"
rm -f "$JAR"
RES=$(printf '%s\n' "$OUT" | sed -n 's/.*-> \([^ ]*\).*/\1/p' | tail -1)
RES=$(python3 -c 'import sys;v=float(sys.argv[1]);print(int(v) if v.is_integer() else v)' "$RES") || { echo "FAIL: unexpected result '$RES'"; exit 1; }
[ "$RES" = 5 ] || { echo "FAIL: demo_calculator_tool(2,3,add) -> $RES (expected 5)"; exit 1; }
echo "PASS: demo_calculator_tool(2,3,add) -> $RES"
